"""Generate directional exposure from IHM natural and artificial coastlines.

The shoreline is used as an offline preprocessing input. The browser only ships
the compact TypeScript profile generated by this script.

For every surf spot the generator:
  * traces rays towards the source of incoming swell every five degrees;
  * starts just seaward of the configured break, then detects headlands,
    islands and opposite shores intersecting those rays;
  * averages a 40-degree fan into ten-degree directional sectors; and
  * retains a small blocked-wave floor for unresolved diffraction and geometry.

COALNE contains high- and low-water polylines rather than land polygons. The
spot's validated `shoreFacingDeg` therefore anchors the seaward half-plane while
the shoreline geometry automatically determines obstruction inside that plane.
"""

from __future__ import annotations

import argparse
import json
import math
import re
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

try:
    import shapefile
except ImportError as error:  # pragma: no cover - developer setup failure
    raise SystemExit(
        "Missing pyshp. Install the shoreline generator dependencies with "
        "`python -m pip install -r scripts/requirements-shoreline.txt`."
    ) from error


WEB_ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = WEB_ROOT / ".generated-shoreline" / "LC"
DEFAULT_SHAPEFILES = (
    SOURCE_ROOT / "COALNE" / "COALNE.shp",
    SOURCE_ROOT / "SLCONS" / "SLCONS.shp",
)
DEFAULT_SPOTS = WEB_ROOT / "src" / "data" / "spots.ts"
DEFAULT_OUTPUT = WEB_ROOT / "src" / "data" / "shorelineExposure.generated.ts"

METRES_PER_LATITUDE_DEGREE = 111_320.0
RAW_BEARING_STEP_DEG = 5
SECTOR_STEP_DEG = 10
FAN_HALF_WIDTH_DEG = 20
SEAWARD_HALF_WIDTH_DEG = 105
TRACE_ORIGIN_OFFSET_M = 100.0
LOCAL_SHORELINE_IGNORE_M = 50.0
MAX_TRACE_M = 90_000.0
GRID_CELL_M = 5_000.0
BLOCKED_TRANSMISSION = 0.08


@dataclass(frozen=True)
class Spot:
    slug: str
    latitude: float
    longitude: float
    shore_facing_deg: float


@dataclass(frozen=True)
class Segment:
    start: tuple[float, float]
    end: tuple[float, float]


def normalize_degrees(value: float) -> float:
    return value % 360.0


def angular_difference(first: float, second: float) -> float:
    return 180.0 - abs(abs(normalize_degrees(first) - normalize_degrees(second)) - 180.0)


def cross(first: tuple[float, float], second: tuple[float, float]) -> float:
    return first[0] * second[1] - first[1] * second[0]


def parse_spots(path: Path) -> list[Spot]:
    source = path.read_text(encoding="utf-8")
    catalogue_match = re.search(
        r"export const surfSpots: SpotProfile\[\] = \[(.*?)\n\]",
        source,
        re.DOTALL,
    )
    if catalogue_match is None:
        raise ValueError(f"Could not find surfSpots in {path}")

    spots: list[Spot] = []
    for block in re.findall(r"^  \{\n(.*?)^  \},?$", catalogue_match.group(1), re.MULTILINE | re.DOTALL):
        slug = re.search(r"slug:\s*'([^']+)'", block)
        latitude = re.search(r"latitude:\s*([-\d.]+)", block)
        longitude = re.search(r"longitude:\s*([-\d.]+)", block)
        shore_facing = re.search(r"shoreFacingDeg:\s*([-\d.]+)", block)
        if not all((slug, latitude, longitude, shore_facing)):
            continue
        spots.append(
            Spot(
                slug=slug.group(1),
                latitude=float(latitude.group(1)),
                longitude=float(longitude.group(1)),
                shore_facing_deg=float(shore_facing.group(1)),
            )
        )

    if not spots:
        raise ValueError(f"No complete spot profiles found in {path}")
    return spots


class ShorelineIndex:
    def __init__(self, shapefile_paths: Iterable[Path], spots: Iterable[Spot]) -> None:
        spot_list = list(spots)
        self.reference_latitude = sum(spot.latitude for spot in spot_list) / len(spot_list)
        self.reference_longitude = sum(spot.longitude for spot in spot_list) / len(spot_list)
        self.metres_per_longitude_degree = METRES_PER_LATITUDE_DEGREE * math.cos(
            math.radians(self.reference_latitude)
        )
        self.segments: list[Segment] = []
        self.grid: dict[tuple[int, int], list[int]] = defaultdict(list)

        longitude_margin = MAX_TRACE_M / self.metres_per_longitude_degree
        latitude_margin = MAX_TRACE_M / METRES_PER_LATITUDE_DEGREE
        min_longitude = min(spot.longitude for spot in spot_list) - longitude_margin
        max_longitude = max(spot.longitude for spot in spot_list) + longitude_margin
        min_latitude = min(spot.latitude for spot in spot_list) - latitude_margin
        max_latitude = max(spot.latitude for spot in spot_list) + latitude_margin

        for shapefile_path in shapefile_paths:
            reader = shapefile.Reader(str(shapefile_path))
            if reader.shapeType != shapefile.POLYLINE:
                raise ValueError(f"Expected a polyline shoreline, received shape type {reader.shapeType}")

            for shape in reader.iterShapes():
                left, bottom, right, top = shape.bbox
                if right < min_longitude or left > max_longitude or top < min_latitude or bottom > max_latitude:
                    continue
                part_starts = list(shape.parts) + [len(shape.points)]
                for start_index, end_index in zip(part_starts, part_starts[1:]):
                    for point_index in range(start_index, end_index - 1):
                        self._add_segment(shape.points[point_index], shape.points[point_index + 1])

    def project(self, longitude: float, latitude: float) -> tuple[float, float]:
        return (
            (longitude - self.reference_longitude) * self.metres_per_longitude_degree,
            (latitude - self.reference_latitude) * METRES_PER_LATITUDE_DEGREE,
        )

    def _add_segment(self, start_lon_lat: list[float], end_lon_lat: list[float]) -> None:
        start = self.project(start_lon_lat[0], start_lon_lat[1])
        end = self.project(end_lon_lat[0], end_lon_lat[1])
        segment_index = len(self.segments)
        self.segments.append(Segment(start, end))

        min_x, max_x = sorted((start[0], end[0]))
        min_y, max_y = sorted((start[1], end[1]))
        for grid_x in range(math.floor(min_x / GRID_CELL_M), math.floor(max_x / GRID_CELL_M) + 1):
            for grid_y in range(math.floor(min_y / GRID_CELL_M), math.floor(max_y / GRID_CELL_M) + 1):
                self.grid[(grid_x, grid_y)].append(segment_index)

    def _ray_candidates(self, origin: tuple[float, float], direction: tuple[float, float]) -> set[int]:
        candidates: set[int] = set()
        sample_step = GRID_CELL_M / 3.0
        sample_count = math.ceil(MAX_TRACE_M / sample_step)
        for sample_index in range(sample_count + 1):
            distance = min(MAX_TRACE_M, sample_index * sample_step)
            grid_x = math.floor((origin[0] + direction[0] * distance) / GRID_CELL_M)
            grid_y = math.floor((origin[1] + direction[1] * distance) / GRID_CELL_M)
            # Neighbouring cells make the candidate lookup robust at grid corners.
            for offset_x in (-1, 0, 1):
                for offset_y in (-1, 0, 1):
                    candidates.update(self.grid.get((grid_x + offset_x, grid_y + offset_y), ()))
        return candidates

    def first_intersection_distance(self, origin: tuple[float, float], bearing_deg: float) -> float | None:
        bearing_radians = math.radians(bearing_deg)
        direction = (math.sin(bearing_radians), math.cos(bearing_radians))
        nearest: float | None = None

        for segment_index in self._ray_candidates(origin, direction):
            segment = self.segments[segment_index]
            segment_vector = (
                segment.end[0] - segment.start[0],
                segment.end[1] - segment.start[1],
            )
            denominator = cross(direction, segment_vector)
            if abs(denominator) < 1e-9:
                continue
            origin_to_start = (segment.start[0] - origin[0], segment.start[1] - origin[1])
            ray_distance = cross(origin_to_start, segment_vector) / denominator
            segment_fraction = cross(origin_to_start, direction) / denominator
            if not (LOCAL_SHORELINE_IGNORE_M < ray_distance <= MAX_TRACE_M):
                continue
            if not (-1e-9 <= segment_fraction <= 1.0 + 1e-9):
                continue
            if nearest is None or ray_distance < nearest:
                nearest = ray_distance
        return nearest


def generate_profile(index: ShorelineIndex, spot: Spot) -> dict[str, object]:
    origin = index.project(spot.longitude, spot.latitude)
    shore_normal_radians = math.radians(spot.shore_facing_deg)
    origin = (
        origin[0] + math.sin(shore_normal_radians) * TRACE_ORIGIN_OFFSET_M,
        origin[1] + math.cos(shore_normal_radians) * TRACE_ORIGIN_OFFSET_M,
    )
    raw_rays: dict[int, tuple[float, float, float | None]] = {}

    for bearing in range(0, 360, RAW_BEARING_STEP_DEG):
        if angular_difference(bearing, spot.shore_facing_deg) > SEAWARD_HALF_WIDTH_DEG:
            raw_rays[bearing] = (BLOCKED_TRANSMISSION, 0.0, 0.0)
            continue
        obstacle_distance = index.first_intersection_distance(origin, bearing)
        is_open = obstacle_distance is None
        raw_rays[bearing] = (
            1.0 if is_open else BLOCKED_TRANSMISSION,
            1.0 if is_open else 0.0,
            obstacle_distance,
        )

    transmission: list[float] = []
    open_fraction: list[float] = []
    nearest_obstacle_km: list[float | None] = []
    fan_offsets = range(-FAN_HALF_WIDTH_DEG, FAN_HALF_WIDTH_DEG + 1, RAW_BEARING_STEP_DEG)

    for sector_bearing in range(0, 360, SECTOR_STEP_DEG):
        samples = [raw_rays[int(normalize_degrees(sector_bearing + offset))] for offset in fan_offsets]
        transmission.append(round(sum(sample[0] for sample in samples) / len(samples), 2))
        open_fraction.append(round(sum(sample[1] for sample in samples) / len(samples), 2))
        obstacle_distances = [sample[2] for sample in samples if sample[2] is not None]
        nearest_obstacle_km.append(
            round(min(obstacle_distances) / 1_000.0, 1) if obstacle_distances else None
        )

    return {
        "intervalDeg": SECTOR_STEP_DEG,
        "shoreFacingDeg": spot.shore_facing_deg,
        "transmission": transmission,
        "openFraction": open_fraction,
        "nearestObstacleKm": nearest_obstacle_km,
    }


def write_typescript(output_path: Path, profiles: dict[str, dict[str, object]], segment_count: int) -> None:
    metadata = {
        "dataset": "IHM LC composite (COALNE + SLCONS)",
        "datasetVersion": "ihm-lc-composite-v3",
        "crs": "EPSG:4326",
        "method": "directional shoreline ray casting",
        "sectorStepDeg": SECTOR_STEP_DEG,
        "rawBearingStepDeg": RAW_BEARING_STEP_DEG,
        "fanHalfWidthDeg": FAN_HALF_WIDTH_DEG,
        "maxTraceKm": MAX_TRACE_M / 1_000,
        "traceOriginOffsetM": TRACE_ORIGIN_OFFSET_M,
        "localIgnoreM": LOCAL_SHORELINE_IGNORE_M,
        "blockedTransmission": BLOCKED_TRANSMISSION,
        "segmentCount": segment_count,
    }
    output = (
        "// Generated by scripts/generate_shoreline_exposure.py from IHM COALNE + SLCONS.\n"
        "// Do not edit by hand; regenerate after changing spots or shoreline inputs.\n\n"
        f"export const shorelineExposureMetadata = {json.dumps(metadata, indent=2, ensure_ascii=False)} as const\n\n"
        f"export const shorelineExposureProfiles = {json.dumps(profiles, indent=2, ensure_ascii=False)} as const\n"
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(output, encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--shapefile", type=Path, action="append", dest="shapefiles")
    parser.add_argument("--spots", type=Path, default=DEFAULT_SPOTS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    shapefile_paths = tuple(args.shapefiles or DEFAULT_SHAPEFILES)
    missing = [str(path) for path in shapefile_paths if not path.exists()]
    if missing:
        raise SystemExit(f"IHM shoreline shapefiles not found: {', '.join(missing)}")
    spots = parse_spots(args.spots)
    shoreline_index = ShorelineIndex(shapefile_paths, spots)
    profiles = {spot.slug: generate_profile(shoreline_index, spot) for spot in spots}
    write_typescript(args.output, profiles, len(shoreline_index.segments))
    print(f"Generated {len(profiles)} profiles from {len(shoreline_index.segments):,} shoreline segments")
    print(f"Output: {args.output}")


if __name__ == "__main__":
    main()

